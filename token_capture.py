"""Token observations for the coding agent's edits, and a stream replay for captured requests.

Captured agent requests run non-streamed so vLLM returns logprobs for every generated token, including the raw
tool-call text its Gemma 4 parser turns into `tool_calls`. That raw text looks like
`<|tool_call>call:edit{edits:[{newText:<|"|>…<|"|>,oldText:<|"|>…<|"|>}],path:<|"|>a.py<|"|>}<tool_call|>`,
with string values unescaped between single `<|"|>` tokens. For the written text of each `edit` and `write` call this
module keeps the tokens that produced it, checked against vLLM's parsed arguments.
See specs/EDIT_CONFIDENCE_PLAN.md.
"""
import bisect
import json
import math
import re
import time

TOP_K = 15
STRING_DELIMITER = '<|"|>'
CALL_START = '<|tool_call>'
# The written text of each captured tool: edit replacements and whole-file writes.
CAPTURED_VALUES = {'edit': 'newText', 'write': 'content'}
ALTERNATIVES = 3
# Tokens at or above both of these keep no alternatives, which keeps records small.
UNCERTAIN = 0.95
RUN_ID = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')


class MappingError(Exception):
    """The raw output cannot be matched to the parsed tool calls exactly."""


def capture_body(body: dict) -> dict:
    """The upstream request for a captured call: non-streamed, with the top-k logprobs at every position."""
    upstream = {key: value for key, value in body.items() if key not in ('stream', 'stream_options')}
    upstream['logprobs'] = True
    upstream['top_logprobs'] = TOP_K
    return upstream


def negentropy(top_logprobs: list, k: int = TOP_K):
    """uqlm's token negentropy: 1 - H / ln k over the renormalized top-k probabilities.

    uqlm leaves positions with fewer than k alternatives unscored; so does this. When vLLM adds the sampled token
    to the list (k + 1 entries), the k most likely are used.
    """
    values = sorted((value for value in top_logprobs if isinstance(value, (int, float)) and math.isfinite(value)), reverse=True)
    if len(values) < k:
        return None
    probabilities = [math.exp(value) for value in values[:k]]
    total = sum(probabilities)
    if total <= 0:
        return None
    entropy = -sum(p / total * math.log(p / total) for p in probabilities if p > 0)
    return max(0.0, min(1.0, 1 - entropy / math.log(k)))


def _raw_text(tokens: list):
    """The generated text and each token's [start, end) in characters of it."""
    pieces, starts, cursor = [], [], 0
    for token in tokens:
        data = bytes(token['bytes']) if isinstance(token.get('bytes'), list) else str(token.get('token', '')).encode('utf-8')
        pieces.append(data)
        starts.append(cursor)
        cursor += len(data)
    raw_bytes = b''.join(pieces)
    try:
        raw = raw_bytes.decode('utf-8')
    except UnicodeDecodeError as exc:
        raise MappingError('The generated bytes are not valid UTF-8.') from exc
    # A character belongs to the token holding its first byte.
    char_bytes, offset = [], 0
    for char in raw:
        char_bytes.append(offset)
        offset += len(char.encode('utf-8'))
    spans = []
    for index, start in enumerate(starts):
        end = starts[index + 1] if index + 1 < len(starts) else len(raw_bytes)
        spans.append((bisect.bisect_left(char_bytes, start), bisect.bisect_left(char_bytes, end)))
    return raw, spans


class _CallParser:
    """Reads one `call:name{...}` block and records the character span of every string value by its path."""

    def __init__(self, text: str, position: int):
        self.text, self.position, self.strings = text, position, []

    def skip(self):
        while self.position < len(self.text) and self.text[self.position] in ' \t\r\n':
            self.position += 1

    def expect(self, literal: str):
        self.skip()
        if not self.text.startswith(literal, self.position):
            raise MappingError(f'Expected {literal!r} in the tool call.')
        self.position += len(literal)

    def call(self):
        self.expect('call:')
        brace = self.text.find('{', self.position)
        if brace < 0:
            raise MappingError('The tool call has no arguments.')
        name = self.text[self.position:brace].strip()
        self.position = brace
        self.object([])
        return name

    def value(self, path: list):
        self.skip()
        if self.text.startswith(STRING_DELIMITER, self.position):
            start = self.position + len(STRING_DELIMITER)
            end = self.text.find(STRING_DELIMITER, start)
            if end < 0:
                raise MappingError('A string value is not closed.')
            self.strings.append((path, start, end))
            self.position = end + len(STRING_DELIMITER)
        elif self.text.startswith('{', self.position):
            self.object(path)
        elif self.text.startswith('[', self.position):
            self.array(path)
        else:
            match = re.compile(r'[^,}\]]*').match(self.text, self.position)
            self.position = match.end()

    def object(self, path: list):
        self.expect('{')
        self.skip()
        if self.text.startswith('}', self.position):
            self.position += 1
            return
        while True:
            self.skip()
            colon = self.text.find(':', self.position)
            if colon < 0:
                raise MappingError('An argument has no value.')
            key = self.text[self.position:colon].strip()
            self.position = colon + 1
            self.value(path + [key])
            self.skip()
            if self.text.startswith(',', self.position):
                self.position += 1
            elif self.text.startswith('}', self.position):
                self.position += 1
                return
            else:
                raise MappingError('Expected , or } in the tool call.')

    def array(self, path: list):
        self.expect('[')
        self.skip()
        if self.text.startswith(']', self.position):
            self.position += 1
            return
        index = 0
        while True:
            self.value(path + [index])
            index += 1
            self.skip()
            if self.text.startswith(',', self.position):
                self.position += 1
            elif self.text.startswith(']', self.position):
                self.position += 1
                return
            else:
                raise MappingError('Expected , or ] in the tool call.')


def _at(arguments, path: list):
    value = arguments
    for key in path:
        if isinstance(key, int) and isinstance(value, list) and key < len(value):
            value = value[key]
        elif isinstance(key, str) and isinstance(value, dict) and key in value:
            value = value[key]
        else:
            return None
    return value


def _utf16_offsets(text: str) -> list:
    offsets, total = [0], 0
    for char in text:
        total += 2 if ord(char) > 0xFFFF else 1
        offsets.append(total)
    return offsets


def edit_tokens(choice: dict) -> list:
    """Token records for the written text of each captured tool call in one completion choice.

    Each call: {"id", "name", "values": [{"path", "tokens"}]}. A token is
    [start, end, logprob, negentropy or None, text, alternatives or None], with start and end in UTF-16 code units of
    the value (JavaScript string offsets) and alternatives as [text, logprob] pairs of the most likely tokens.
    Values whose tokens do not reproduce vLLM's parsed argument exactly are left out.
    """
    calls = (choice.get('message') or {}).get('tool_calls') or []
    tokens = (choice.get('logprobs') or {}).get('content') or []
    if not calls or not tokens:
        return []
    raw, spans = _raw_text(tokens)
    utf16 = _utf16_offsets(raw)
    starts = [span[0] for span in spans]
    blocks, position = [], raw.find(CALL_START)
    while position >= 0:
        parser = _CallParser(raw, position + len(CALL_START))
        name = parser.call()
        blocks.append((name, parser.strings))
        position = raw.find(CALL_START, parser.position)
    if len(blocks) != len(calls):
        raise MappingError('The raw output and the parsed tool calls disagree.')
    records = []
    for (name, strings), call in zip(blocks, calls):
        function = call.get('function') or {}
        if function.get('name') != name or name not in CAPTURED_VALUES:
            continue
        try:
            arguments = json.loads(function.get('arguments') or '{}')
        except json.JSONDecodeError:
            continue
        values = []
        for path, start, end in strings:
            if not path or path[-1] != CAPTURED_VALUES[name] or _at(arguments, path) != raw[start:end]:
                continue
            first = bisect.bisect_left(starts, start)
            inside = []
            for index in range(first, len(spans)):
                token_start, token_end = spans[index]
                if token_start >= end:
                    break
                inside.append(index)
            # A token reaching past the value's delimiters would blur its boundary; skip such values.
            if any(spans[index][1] > end for index in inside) or (first > 0 and spans[first - 1][1] > start):
                continue
            records_for_value = []
            for index in inside:
                token_start, token_end = spans[index]
                if token_start == token_end:
                    continue
                token = tokens[index]
                logprob = token.get('logprob')
                if not isinstance(logprob, (int, float)) or not math.isfinite(logprob):
                    raise MappingError('A token has no logprob.')
                top = [entry for entry in (token.get('top_logprobs') or []) if isinstance(entry, dict)]
                score = negentropy([entry.get('logprob') for entry in top])
                uncertain = math.exp(logprob) < UNCERTAIN or (score is not None and score < UNCERTAIN)
                alternatives = None
                if uncertain and top:
                    ranked = sorted((entry for entry in top if isinstance(entry.get('logprob'), (int, float))), key=lambda entry: -entry['logprob'])
                    alternatives = [[str(entry.get('token', '')), round(entry['logprob'], 5)] for entry in ranked[:ALTERNATIVES]]
                records_for_value.append([
                    utf16[token_start] - utf16[start], utf16[token_end] - utf16[start], round(logprob, 5),
                    None if score is None else round(score, 5), raw[token_start:token_end], alternatives,
                ])
            values.append({'path': path, 'tokens': records_for_value})
        if values:
            records.append({'id': call.get('id'), 'name': name, 'values': values})
    return records


def sse_events(result: dict, include_usage: bool) -> list:
    """Replay a non-streamed chat completion as OpenAI-style stream chunks, ending with [DONE]."""
    base = {'id': result.get('id'), 'object': 'chat.completion.chunk', 'created': result.get('created') or int(time.time()),
            'model': result.get('model')}
    chunks = []
    for choice in result.get('choices') or []:
        index = choice.get('index', 0)
        message = choice.get('message') or {}
        delta = {'role': 'assistant'}
        reasoning = message.get('reasoning_content') or message.get('reasoning')
        if reasoning:
            delta['reasoning_content'] = reasoning
        if message.get('content'):
            delta['content'] = message['content']
        chunks.append({**base, 'choices': [{'index': index, 'delta': delta, 'finish_reason': None}]})
        for position, call in enumerate(message.get('tool_calls') or []):
            function = call.get('function') or {}
            chunks.append({**base, 'choices': [{'index': index, 'finish_reason': None, 'delta': {'tool_calls': [{
                'index': position, 'id': call.get('id'), 'type': 'function',
                'function': {'name': function.get('name'), 'arguments': function.get('arguments') or ''}}]}}]})
        chunks.append({**base, 'choices': [{'index': index, 'delta': {}, 'finish_reason': choice.get('finish_reason') or 'stop'}]})
    if include_usage and result.get('usage'):
        chunks.append({**base, 'choices': [], 'usage': result['usage']})
    return [f'data: {json.dumps(chunk)}\n\n'.encode() for chunk in chunks] + [b'data: [DONE]\n\n']
